PROMPT Checking connected schema...
DECLARE
    v_user VARCHAR2(128);
BEGIN
    SELECT USER INTO v_user FROM DUAL;
    IF v_user <> 'OPERA_CFG_APP' THEN
        RAISE_APPLICATION_ERROR(
            -20000,
            'This script must be executed connected as OPERA_CFG_APP. Current user is ' || v_user
        );
    END IF;
END;
